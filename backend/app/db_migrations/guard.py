"""Safety checks for staged schema metadata and Alembic autogeneration."""

from __future__ import annotations

from sqlalchemy import MetaData


def assert_autogenerate_metadata_complete(metadata: MetaData) -> None:
    """Reject autogeneration while metadata contains reference-only tables.

    Partial domain models are useful for isolated contract tests, but must not
    be treated as the authoritative application schema by Alembic. Every
    reference-only table must be replaced by its complete domain definition
    before a baseline or autogenerated migration can be produced.
    """
    incomplete = sorted(
        table.name
        for table in metadata.tables.values()
        if table.info.get("reference_only") is True
    )
    if incomplete:
        names = ", ".join(incomplete)
        raise RuntimeError(
            "Alembic autogeneration is blocked because schema metadata is "
            f"incomplete; replace reference-only table definitions first: {names}"
        )
